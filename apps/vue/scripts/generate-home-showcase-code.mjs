import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { codeToTokens } from 'shiki';

const dirname = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(dirname, '..');
const workspaceRoot = path.resolve(appRoot, '../..');
const outputFile = path.join(appRoot, 'lib/home-showcase-code.ts');
const sourceFile = path.join(appRoot, 'components/home-showcase-demo.vue');

// Generation contract: read the actual SFC rendered by the homepage. Balanced, non-nested markers annotate
// imports, refs, and template blocks while being omitted from the editor output.
const markerPattern = /@showcase-stage-(\d+)-(start|end)/;
const blockCounts = new Map();
const stages = new Map();
const sourceLines = [];
let activeBlock;
for (const [sourceIndex, source] of fs.readFileSync(sourceFile, 'utf8').split('\n').entries()) {
	const marker = source.match(markerPattern);
	if (marker) {
		const stage = Number(marker[1]);
		if (marker[2] === 'start') {
			if (activeBlock) throw new Error(`Nested showcase marker at ${path.relative(appRoot, sourceFile)}:${sourceIndex + 1}`);
			const block = (blockCounts.get(stage) ?? 0) + 1;
			blockCounts.set(stage, block);
			activeBlock = { stage, block, startLine: sourceLines.length };
		} else {
			if (!activeBlock || activeBlock.stage !== stage) throw new Error(`Unmatched showcase marker at ${path.relative(appRoot, sourceFile)}:${sourceIndex + 1}`);
			const block = { ...activeBlock, endLine: sourceLines.length - 1 };
			stages.set(stage, [...(stages.get(stage) ?? []), block]);
			activeBlock = undefined;
		}
		continue;
	}
	if (source.includes('@showcase-stage-')) throw new Error(`Invalid showcase marker at ${path.relative(appRoot, sourceFile)}:${sourceIndex + 1}`);
	sourceLines.push({ stage: activeBlock?.stage ?? 0, block: activeBlock?.block ?? 0, source });
}
if (activeBlock) throw new Error(`Unclosed stage ${activeBlock.stage} showcase marker in ${path.relative(appRoot, sourceFile)}`);

function escapeHtml(value) {
	return value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
}

// Shiki's Vue grammar handles SFC sections, directives, bindings, template tags, and TypeScript together.
// Runtime code only controls line visibility, diff state, the unique caret, and editor scrolling.
const highlighted = await codeToTokens(sourceLines.map((line) => line.source).join('\n'), { lang: 'vue', theme: 'github-dark' });
const lines = sourceLines.map((line, index) => ({
	...line,
	html: highlighted.tokens[index]?.map((token) => `<span style="color:${token.color}">${escapeHtml(token.content)}</span>`).join('') || ' ',
}));
const stageMetadata = [...stages].sort(([left], [right]) => left - right).map(([stage, blocks]) => ({ stage, blocks }));

fs.writeFileSync(
	outputFile,
	`// Generated by scripts/generate-home-showcase-code.mjs. Do not edit manually.\nexport const homeShowcaseMeta = ${JSON.stringify({ fileName: path.basename(sourceFile), language: 'VUE' }, null, '\t')} as const;\nexport const homeShowcaseStages = ${JSON.stringify(stageMetadata, null, '\t')} as const;\nexport const homeShowcaseCodeLines = ${JSON.stringify(lines, null, '\t')} as const;\n`,
);
const formatter = path.join(workspaceRoot, 'node_modules/.bin/oxfmt');
if (fs.existsSync(formatter)) spawnSync(formatter, [outputFile], { stdio: 'inherit' });
console.log(`Generated ${path.relative(appRoot, outputFile)} from ${path.relative(appRoot, sourceFile)} with ${lines.length} Shiki-highlighted lines`);
