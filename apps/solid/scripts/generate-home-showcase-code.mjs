import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

import { codeToTokens } from 'shiki';

const dirname = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(dirname, '..');
const workspaceRoot = path.resolve(appRoot, '../..');
const sourceFile = path.join(appRoot, 'src/components/home-showcase-demo.tsx');
const outputFile = path.join(appRoot, 'src/generated/home-showcase-code.ts');

function escapeHtml(value) {
	return value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
}

let stage = 0;
let block = 0;
const blockCounts = new Map();
const sourceLines = [];
for (const source of fs.readFileSync(sourceFile, 'utf8').split('\n')) {
	const marker = source.match(/@showcase-stage-(\d)-(start|end)/);
	if (marker) {
		if (marker[2] === 'start') {
			stage = Number(marker[1]);
			block = (blockCounts.get(stage) ?? 0) + 1;
			blockCounts.set(stage, block);
		} else {
			stage = 0;
			block = 0;
		}
		continue;
	}
	sourceLines.push({ source, stage, block });
}

const highlighted = await codeToTokens(sourceLines.map((line) => line.source).join('\n'), { lang: 'tsx', theme: 'github-dark' });
const lines = sourceLines.map((line, index) => ({
	...line,
	html:
		highlighted.tokens[index]
			?.map((token) => {
				const styles = [`color:${token.color}`];
				if (token.fontStyle & 1) styles.push('font-style:italic');
				if (token.fontStyle & 2) styles.push('font-weight:700');
				if (token.fontStyle & 4) styles.push('text-decoration:underline');
				return `<span style="${styles.join(';')}">${escapeHtml(token.content)}</span>`;
			})
			.join('') || ' ',
}));

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
fs.writeFileSync(
	outputFile,
	`// This file is generated by scripts/generate-home-showcase-code.mjs. Do not edit manually.\nexport type HomeShowcaseCodeLine = { source: string; html: string; stage: number; block: number };\nexport const homeShowcaseCodeLines: HomeShowcaseCodeLine[] = ${JSON.stringify(lines, null, '\t')};\n`,
);
const formatter = path.join(workspaceRoot, 'node_modules/.bin/oxfmt');
if (fs.existsSync(formatter)) spawnSync(formatter, [outputFile], { stdio: 'inherit' });
console.log(`Generated ${path.relative(appRoot, outputFile)} with ${lines.length} Shiki-highlighted lines`);
